import { chromium } from '@playwright/test';
const b = await chromium.launch();
const pg = await b.newPage({ viewport: { width: 1400, height: 900 } });
pg.on('pageerror', (e) => console.log('PAGEERR', e.stack));
pg.on('console', (m) => console.log('CONSOLE', m.type(), m.text()));
await pg.goto('http://localhost:4391/playground/', { waitUntil: 'networkidle' });
await pg.locator('#' + process.argv[2]).scrollIntoViewIfNeeded();
await pg.waitForTimeout(4000);
console.log(await pg.locator('#' + process.argv[2]).innerText());
await b.close();
